const DICTS: Record<Lang, Dict> = { en, hi };

type Ctx = {
  lang: Lang;
  t: (key: string) => string;
  setLang: (l: Lang) => Promise<void>;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const detected: Lang = useMemo(() => {
    try {
      const locale = Localization.getLocales?.()[0]?.languageCode || "en";
      return locale.toLowerCase().startsWith("hi") ? "hi" : "en";
    } catch {
      return "en";
    }
  }, []);
  const [lang, setLangState] = useState<Lang>(detected);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    (async () => {
      const stored = await storage.getItem<Lang>(LANG_KEY, "" as any);
      if (stored === "en" || stored === "hi") setLangState(stored);
      setReady(true);
    })();
  }, []);

  const setLang = async (l: Lang) => {
    setLangState(l);
    await storage.setItem(LANG_KEY, l);
  };

  const t = (key: string): string => {
    const d = DICTS[lang];
    return d[key] ?? DICTS.en[key] ?? key;
  };

  if (!ready) return null;
  return <I18nContext.Provider value={{ lang, t, setLang }}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be inside I18nProvider");
  return ctx;
}
